/** استخراج مسیر SVG آیکون‌های Material Symbols → src/components/ui/glyphs.ts */
import { readFileSync, writeFileSync } from 'node:fs'

const NAMES = [
  // حال‌وهوا (mood)
  'sentiment_very_dissatisfied',
  'sentiment_dissatisfied',
  'sentiment_neutral',
  'sentiment_satisfied',
  'sentiment_very_satisfied',
  // هوا
  'wb_sunny',
  'cloud',
  'rainy',
  'ac_unit',
  'air',
  'thunderstorm',
  // دسته‌ی هزینه
  'restaurant',
  'directions_bus',
  'home',
  'health_and_safety',
  'sports_esports',
  'inventory_2',
  // قالب‌ها
  'calendar_today',
  'shopping_cart',
  'groups',
  'code',
  'flight',
  'description',
  // عمومی
  'local_fire_department',
  'check_circle',
  'error',
  'music_note',
  'close',
  'mail',
  'bar_chart',
  'keyboard_command_key',
  'event',
  'task_alt',
]

const entries = []
for (const name of NAMES) {
  const file = `node_modules/@material-symbols/svg-400/outlined/${name}.svg`
  const svg = readFileSync(file, 'utf8')
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  if (!inner.includes('<path')) throw new Error(`no path in ${name}`)
  entries.push(`  ${name}: \`${inner.trim()}\`,`)
}

const out = `/* GENERATED by scripts/extract-glyphs.mjs — دستی ویرایش نشود */
export type GlyphName =
${NAMES.map((n) => `  | '${n}'`).join('\n')}

export const GLYPHS: Record<GlyphName, string> = {
${entries.join('\n')}
}
`
writeFileSync('src/components/ui/glyphs.ts', out)
console.log(`extracted ${NAMES.length} glyphs`)
